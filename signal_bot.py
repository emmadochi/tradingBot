def send_email(subject: str, body: str) -> None:
    """Send a plain-text email via SMTP SSL. No-ops silently if credentials are not set."""
    if not all([EMAIL_SMTP_HOST, EMAIL_SENDER, EMAIL_PASSWORD, EMAIL_RECIPIENT]):
        return  # notifications not configured
    try:
        msg = MIMEText(body, "plain", "utf-8")
        msg["Subject"] = subject
        msg["From"]    = EMAIL_SENDER
        msg["To"]      = EMAIL_RECIPIENT
        ctx = ssl.create_default_context()
        if EMAIL_SMTP_PORT == 587:
            with smtplib.SMTP(EMAIL_SMTP_HOST, EMAIL_SMTP_PORT, timeout=10) as srv:
                srv.ehlo()
                srv.starttls(context=ctx)
                srv.login(EMAIL_SENDER, EMAIL_PASSWORD)
                srv.sendmail(EMAIL_SENDER, EMAIL_RECIPIENT, msg.as_string())
        else:  # 465 — SMTP over SSL
            with smtplib.SMTP_SSL(EMAIL_SMTP_HOST, EMAIL_SMTP_PORT, context=ctx, timeout=10) as srv:
                srv.login(EMAIL_SENDER, EMAIL_PASSWORD)
                srv.sendmail(EMAIL_SENDER, EMAIL_RECIPIENT, msg.as_string())
    except Exception as exc:
        print(f"[Email] Failed to send notification: {exc}")


