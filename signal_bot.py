# ------------------------- Indicators --------------------------

def ema(series: pd.Series, period: int) -> pd.Series:
    return series.ewm(span=period, adjust=False).mean()


def atr(df: pd.DataFrame, period: int) -> pd.Series:
    high, low, close = df["high"], df["low"], df["close"]
    prev_close = close.shift(1)
    tr = pd.concat(
        [(high - low), (high - prev_close).abs(), (low - prev_close).abs()], axis=1
    ).max(axis=1)
    return tr.ewm(alpha=1 / period, adjust=False).mean()


# ---------------------- Candlestick patterns ----------------------

def candle_metrics(row):
    o, h, l, c = row["open"], row["high"], row["low"], row["close"]
    body = abs(c - o)
    rng = max(h - l, 1e-9)
    upper_wick = h - max(o, c)
    lower_wick = min(o, c) - l
    return body, rng, upper_wick, lower_wick


def is_bullish(row) -> bool:
    return row["close"] > row["open"]


def is_bearish(row) -> bool:
    return row["close"] < row["open"]


def is_bullish_engulfing(prev, curr) -> bool:
    return (
        is_bearish(prev) and is_bullish(curr)
        and curr["close"] >= prev["open"] and curr["open"] <= prev["close"]
    )


def is_bearish_engulfing(prev, curr) -> bool:
    return (
        is_bullish(prev) and is_bearish(curr)
        and curr["open"] >= prev["close"] and curr["close"] <= prev["open"]
    )


def is_hammer(row) -> bool:
    body, rng, upper, lower = candle_metrics(row)
    return lower >= body * 2 and upper <= body * 0.6 and body / rng >= 0.05


def is_shooting_star(row) -> bool:
    body, rng, upper, lower = candle_metrics(row)
    return upper >= body * 2 and lower <= body * 0.6 and body / rng >= 0.05


def is_morning_star(c1, c2, c3) -> bool:
    b1, _, _, _ = candle_metrics(c1)
    b2, _, _, _ = candle_metrics(c2)
    mid1 = (c1["open"] + c1["close"]) / 2
    return is_bearish(c1) and b1 > 0 and b2 < b1 * 0.5 and is_bullish(c3) and c3["close"] > mid1


def is_evening_star(c1, c2, c3) -> bool:
    b1, _, _, _ = candle_metrics(c1)
    b2, _, _, _ = candle_metrics(c2)
    mid1 = (c1["open"] + c1["close"]) / 2
    return is_bullish(c1) and b1 > 0 and b2 < b1 * 0.5 and is_bearish(c3) and c3["close"] < mid1


def detect_pattern(df_tail: pd.DataFrame):
    """df_tail = last 3 candles, chronological. Returns (pattern_name, direction) or (None, None)."""
    if len(df_tail) < 3:
        return None, None
    c1, c2, c3 = df_tail.iloc[-3], df_tail.iloc[-2], df_tail.iloc[-1]

    if is_morning_star(c1, c2, c3):
        return "Morning Star", "BUY"
    if is_evening_star(c1, c2, c3):
        return "Evening Star", "SELL"
    if is_bullish_engulfing(c2, c3):
        return "Bullish Engulfing", "BUY"
    if is_bearish_engulfing(c2, c3):
        return "Bearish Engulfing", "SELL"
    if is_hammer(c3):
        return "Hammer", "BUY"
    if is_shooting_star(c3):
        return "Shooting Star", "SELL"
    return None, None


# ---------------------- Swings & S/R levels ----------------------

def find_swings(df: pd.DataFrame, lookback: int = SWING_LOOKBACK):
    """Returns (swing_highs, swing_lows) as lists of (epoch, price), chronological."""
    highs, lows = [], []
    h, l = df["high"].values, df["low"].values
    for i in range(lookback, len(df) - lookback):
        window_h = h[i - lookback: i + lookback + 1]
        window_l = l[i - lookback: i + lookback + 1]
        if h[i] == window_h.max():
            highs.append((df["epoch"].iloc[i], h[i]))
        if l[i] == window_l.min():
            lows.append((df["epoch"].iloc[i], l[i]))
    return highs, lows


def cluster_levels(points, tolerance_pct: float = SR_CLUSTER_PCT):
    """Merge nearby swing prices into representative S/R levels."""
    if not points:
        return []
    values = sorted(p[1] for p in points)
    clusters = [[values[0]]]
    for v in values[1:]:
        if abs(v - clusters[-1][-1]) / clusters[-1][-1] * 100 <= tolerance_pct:
            clusters[-1].append(v)
        else:
            clusters.append([v])
    return [sum(c) / len(c) for c in clusters]


def determine_trend(df: pd.DataFrame, swing_highs, swing_lows) -> str:
    if len(swing_highs) >= 2 and len(swing_lows) >= 2:
        higher_high = swing_highs[-1][1] > swing_highs[-2][1]
        higher_low = swing_lows[-1][1] > swing_lows[-2][1]
        lower_high = swing_highs[-1][1] < swing_highs[-2][1]
        lower_low = swing_lows[-1][1] < swing_lows[-2][1]
        if higher_high and higher_low:
            return "UP"
        if lower_high and lower_low:
            return "DOWN"
    ema_series = ema(df["close"], TREND_EMA_PERIOD)
    if len(ema_series) > 10:
        if ema_series.iloc[-1] > ema_series.iloc[-10]:
            return "UP"
        elif ema_series.iloc[-1] < ema_series.iloc[-10]:
            return "DOWN"
    return "RANGE"


def nearest_below(levels, price):
    below = [lv for lv in levels if lv <= price]
    return max(below) if below else None


def nearest_above(levels, price):
    above = [lv for lv in levels if lv >= price]
    return min(above) if above else None


def pct_distance(a, b) -> float:
    return abs(a - b) / b * 100 if b else float("inf")


def log_signal(row: dict):
    file_exists = os.path.isfile(LOG_FILE)
    with open(LOG_FILE, "a", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=row.keys())
        if not file_exists:
            writer.writeheader()
        writer.writerow(row)


# ------------------------- Symbol context -------------------------

class SymbolContext:
    def __init__(self, symbol: str):
        self.symbol = symbol
        self.trend = "RANGE"
        self.support_levels: list[float] = []
        self.resistance_levels: list[float] = []
        self.ltf_candles = deque(maxlen=LTF_CANDLE_COUNT)
        self.last_signal_epoch = None
        # Tracks how many times price has tested each S/R level (key = rounded level)
        self.level_touches: dict[float, int] = {}


